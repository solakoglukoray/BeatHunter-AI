"""
BeatHunter AI — classical audio features.

SINGLE SOURCE OF TRUTH. The catalogue builder and the query path must both call
extract_features(); they must never each have their own copy.

That rule exists because the previous pipeline broke exactly this way: the training
spectrograms and the inference spectrograms were generated by two separate blocks of
code, drifted apart, and fed the model an input distribution it had never seen. It went
unnoticed for months. One function, both sides, no exceptions.

Why these features
──────────────────
Measured against the fine-tuned EfficientNetB3 on identical held-out tracks
(GroupShuffleSplit by track, so no song appears on both sides):

    artist      CNN 0.8x chance   |   these features + LogReg 16.7x
    genre       CNN 0.7x chance   |   these features + LogReg  9.7x

The CNN scored below chance. These are 102 numbers per track, ~345 ms to compute on one
core, and they beat it by more than twenty-fold. They are not a clever choice — MFCC
summaries are the standard timbre descriptor — which is rather the point.

Deliberately excluded as too slow for the gain: HPSS (librosa.effects.harmonic),
chroma_cqt, and beat_track. With those the same extraction took 32+ minutes for 1,549
tracks and did not finish; without them it does 14,235 in 14 minutes.
"""

import numpy as np
import librosa

SAMPLE_RATE = 22050
DURATION    = 30      # seconds analysed from the start of the track
N_MFCC      = 20
FEATURE_DIM = 102     # asserted below — a mismatch here silently corrupts the catalogue


def extract_features(y, sr=SAMPLE_RATE):
    """
    Summarises a waveform as a fixed-length descriptor.

    Returns a float32 array of FEATURE_DIM, or None if the audio is too short to
    describe (under 5 seconds).
    """
    if y is None or len(y) < sr * 5:
        return None

    mfcc     = librosa.feature.mfcc(y=y, sr=sr, n_mfcc=N_MFCC)
    dmfcc    = librosa.feature.delta(mfcc)          # how the timbre moves, not just its mean
    contrast = librosa.feature.spectral_contrast(y=y, sr=sr)
    cent     = librosa.feature.spectral_centroid(y=y, sr=sr)
    roll     = librosa.feature.spectral_rolloff(y=y, sr=sr)
    zcr      = librosa.feature.zero_crossing_rate(y)
    rms      = librosa.feature.rms(y=y)

    feat = np.concatenate([
        mfcc.mean(1), mfcc.std(1),
        dmfcc.mean(1), dmfcc.std(1),
        contrast.mean(1), contrast.std(1),
        [cent.mean(), cent.std(), roll.mean(), roll.std(),
         zcr.mean(), zcr.std(), rms.mean(), rms.std()],
    ]).astype(np.float32)

    if feat.shape[0] != FEATURE_DIM:
        raise ValueError(
            f"feature dim {feat.shape[0]} != FEATURE_DIM {FEATURE_DIM}. "
            "The catalogue and the classifier were built against FEATURE_DIM; "
            "changing the feature set means rebuilding both (see train_classic.py)."
        )
    return feat


def extract_from_file(path, sr=SAMPLE_RATE, duration=DURATION):
    """Loads audio and summarises it. Returns None if unreadable or too short."""
    try:
        y, _ = librosa.load(path, sr=sr, duration=duration)
    except Exception:
        return None
    return extract_features(y, sr)
